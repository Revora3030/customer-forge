/**
 * Regenerates src/lib/sitemap-lastmod.generated.ts from git history.
 *
 *   bun scripts/gen-sitemap-lastmod.ts
 *
 * Needs full git history (`git fetch --unshallow`) so a file last changed
 * before a shallow clone's cut-off is not dated to the cut-off. Dates are the
 * author-independent committer date, in UTC, of the last commit touching each
 * source file. Run it before a release; commit the result.
 */
import { execFileSync } from "node:child_process";
import { readdirSync, writeFileSync } from "node:fs";
import { LASTMOD_SOURCE_GROUPS } from "../src/lib/sitemap-lastmod-sources";

const root = new URL("..", import.meta.url).pathname;
const git = (...args: string[]) => execFileSync("git", args, { cwd: root, encoding: "utf8", env: { ...process.env, TZ: "UTC" } }).trim();

if (git("rev-parse", "--is-shallow-repository") === "true") {
  throw new Error("Shallow clone: run `git fetch --unshallow` first, or dates will be wrong.");
}

const fileDate = (file: string): string | undefined => {
  const out = git("log", "-1", "--format=%cd", "--date=format-local:%Y-%m-%d", "--", file);
  return out || undefined;
};


const newest = (files: readonly string[]) =>
  files.map(fileDate).filter((d): d is string => !!d).sort().at(-1);

const groups: Record<string, string> = {};
for (const [key, files] of Object.entries(LASTMOD_SOURCE_GROUPS)) {
  const date = newest(files);
  if (!date) throw new Error(`No git history for any source of group ${key}`);
  groups[key] = date;
}

const docs: Record<string, string> = {};
for (const kind of ["compare", "local"] as const) {
  const dir = `src/content/seo/${kind}`;
  for (const name of readdirSync(new URL(`../${dir}`, import.meta.url)).sort()) {
    if (!name.endsWith(".md") || name === "index.md") continue;
    const date = fileDate(`${dir}/${name}`);
    if (date) docs[`${kind}/${name.replace(/\.md$/, "")}`] = date;
  }
}

const generatedAt = git("log", "-1", "--format=%cd", "--date=format-local:%Y-%m-%d", "HEAD");
const body = `// GENERATED by scripts/gen-sitemap-lastmod.ts from git history. Do not edit by hand.
export const SITEMAP_LASTMOD: {
  generatedAt: string;
  groups: Record<string, string>;
  docs: Record<string, string>;
} = ${JSON.stringify({ generatedAt, groups, docs }, null, 2)};
`;
writeFileSync(new URL("../src/lib/sitemap-lastmod.generated.ts", import.meta.url), body);
console.log(`groups: ${Object.keys(groups).length}, docs: ${Object.keys(docs).length}, generatedAt ${generatedAt}`);
