/**
 * Shared shapes for the first-build starter-picture lane.
 *
 * Kept free of any server-only import so the quality gate, the builder UI and the
 * tests can all use the same types.
 */

export type FirstBuildImageAsset = {
  slot: string;
  label: string;
  altText: string;
  path: string;
  mediaId: string | null;
  provider: string;
  model: string;
  prompt: string;
  placement: string[];
  /** Positive renderer-safe ratio authored by the AI, normalized to `a:b`. */
  aspectRatio: string;
  /**
   * Where the picture really came from. `owner` is the business's own photo
   * (the only kind that may be shown as completed work); `generated` and
   * `stock` pictures are illustrative only. Absent means "decide from provider".
   */
  assetSource?: "owner" | "generated" | "stock";
  /** The owner's media-library category (work, premises, team, hero …), when known. */
  category?: string | null;
  /** The real service this picture illustrates, as authored by the AI campaign. */
  serviceName?: string | null;
  /** Stock licence code and credit line, carried so stock is never shown unlicensed. */
  license?: string | null;
  attribution?: string | null;
  /** Pixel size, when known (read from the generated bytes or the stock library). */
  width?: number | null;
  height?: number | null;
  /** False when the picture is too small to fill the screen; the renderer frames it instead. */
  fullBleed?: boolean;
};

export type FirstBuildImageSource = "standard" | "premium" | "none";

export type FirstBuildImageEvidence = {
  status: "generated" | "owner_photos" | "blocked" | "failed";
  requested: number;
  generated: number;
  /** Pictures actually attached to the site, filled in after materialization. */
  attached: number;
  skipped: { slot: string; label: string; reason: string }[];
  /** Pictures that were made but rejected by the quality gate. */
  rejected?: { slot: string; label: string; reason: string }[];
  /** Pictures kept but framed, because they were too small to fill the screen. */
  demoted?: { slot: string; label: string; reason: string }[];
  provider: string | null;
  models: string[];
  /** Quality lane that produced the accepted pictures. */
  source?: FirstBuildImageSource;
  /** Plain-language note about paid picture availability and the spending cap. */
  paidNote?: string;
  /** Total paid spend for this build, in microcents. Zero for the free lane. */
  paidCostMicrocents?: number;
  message: string;
};
